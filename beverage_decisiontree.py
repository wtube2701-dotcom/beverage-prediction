import pandas as pd
import matplotlib.pyplot as plt
from collections import Counter

# Read the classes file
with open('/content/classes.txt', 'r') as f:
    lines = [line.strip() for line in f.readlines() if line.strip()]

# Perform EDA
total_lines = len(lines)
unique_classes = set(lines)
class_counts = Counter(lines)

print(f"Total items: {total_lines}")
print(f"Unique classes count: {len(unique_classes)}")
print("\nClass Distributions:")
for cls, count in class_counts.most_common():
    print(f" - {cls}: {count} ({count/total_lines*100:.2f}%)")

# Generate a pie chart of the classes
if class_counts:
    labels, values = zip(*class_counts.most_common())

    plt.figure(figsize=(8, 8))
    plt.pie(values, labels=labels, autopct='%1.1f%%', startangle=140, colors=plt.cm.Paired.colors)
    plt.title('Distribution of Classes')
    plt.axis('equal')
    plt.show()
else:
    print("No data available to plot.")

"""### Machine Learning with a Decision Tree
Since we only have the class text names (targets), we need some features to train a model. We will convert the text strings to numerical features using `TfidfVectorizer` (treating the labels themselves as text input for demonstration), perform an 80/20 train/test split, and train a `DecisionTreeClassifier`.
"""

from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.tree import DecisionTreeClassifier
from sklearn import metrics

# Prepare dummy features based on the labels for demonstration purposes
# In a real scenario, you would have descriptive feature columns corresponding to these classes
X = lines
y = lines

# Vectorize the text data to create numerical features
vectorizer = TfidfVectorizer()
X_vectorized = vectorizer.fit_transform(X)

# Split the dataset into 80% training and 20% testing
X_train, X_test, y_train, y_test = train_test_split(
    X_vectorized, y, test_size=0.20, random_state=42
)

print(f"Training set size: {X_train.shape[0]} samples")
print(f"Testing set size: {X_test.shape[0]} samples")

# Initialize and train the Decision Tree Classifier
clf = DecisionTreeClassifier(random_state=42)
clf.fit(X_train, y_train)

# Predict the response for the test dataset
y_pred = clf.predict(X_test)

# Model Accuracy
accuracy = metrics.accuracy_score(y_test, y_pred)
print(f"Decision Tree Model Accuracy: {accuracy * 100:.2f}%")

# Display classification report
print("\nClassification Report:")
print(metrics.classification_report(y_test, y_pred, zero_division=0))

